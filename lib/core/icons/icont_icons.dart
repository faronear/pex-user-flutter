  /// 解析 `<uni-icons type="...">`。
  static PexGlyph? uni(String? type) {
    if (type == null || type.isEmpty) return null;
    final String key = type.startsWith('uniui-') ? type : 'uniui-$type';
    final int? codepoint = uniui[key];
    return codepoint == null ? null : PexGlyph(codepoint, PexIconFonts.uniicons);
  }

  /// 解析 icont 家族图标。
  static PexGlyph? icont(String? type) {
    if (type == null || type.isEmpty) return null;
    final String key = type.startsWith('icont-') ? type : 'icont-$type';
    final int? codepoint = icontGlyphs[key];
    return codepoint == null ? null : PexGlyph(codepoint, PexIconFonts.icont);
  }

  /// 用源项目记录的 `iconPrefix` / `iconType` 解析图标。
  static PexGlyph? byPrefix(String? prefix, String? type) =>
      (prefix == 'icont') ? icont(type) : uni(type);
